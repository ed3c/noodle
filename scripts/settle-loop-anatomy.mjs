// Build-time geometry proof. Usage: node scripts/settle-loop-anatomy.mjs /path/to/anatomy/kit
// The installed Anatomy audit is a developer tool, never a browser/runtime dependency.
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { spawnSync } from "node:child_process";
const [, , kit] = process.argv;
if (!kit) {
  throw new Error("Pass the installed Anatomy kit directory.");
}
const A = await import(pathToFileURL(join(resolve(kit), "audit.mjs")));
const source = new URL("../ui/src/client/loop-anatomy.mjs", import.meta.url);
const target = new URL("../ui/src/client/anatomy/geometry-orders.mjs", import.meta.url);
const tmp = mkdtempSync(join(tmpdir(), "noodle-anatomy-"));
try {
  let code = readFileSync(source, "utf8");
  code = code.replace(/import \{ geometryOrders \} from .*?;\n/, "");
  code = code
    .replace("  slabOf,", "  slabOf as rawSlab,")
    .replace("  cylinder,", "  cylinder as rawCylinder,")
    .replace("  extrude,", "  extrude as rawExtrude,");
  code = code.replace(
    '"./anatomy/iso-kit.mjs"',
    JSON.stringify(new URL("../ui/src/client/anatomy/iso-kit.mjs", import.meta.url).href),
  );
  const adapter = `import * as A from ${JSON.stringify(pathToFileURL(join(resolve(kit), "audit.mjs")).href)};
function slabOf(...args) { return {...rawSlab(...args),world:A.slab(args[0],args[1],args[2],{},args[4])}; }
function cylinder(...args) { return {...rawCylinder(...args),world:A.cylinder(...args.slice(0,5))}; }
function extrude(...args) { return {...rawExtrude(...args),world:A.extruded(...args.slice(0,3))}; }
`;
  code = code.replace("const machines =", `${adapter}const machines =`);
  if (!code.includes("  const settled = geometryOrders[key];")) {
    throw new Error("Geometry extraction boundary changed.");
  }
  code = code.replace(
    "  const settled = geometryOrders[key];",
    "  return {p,parts};\n  const settled = geometryOrders[key];",
  );
  const module = join(tmp, "geometry.mjs");
  writeFileSync(module, code);
  const { mechanismFigure, geometryFingerprint } = await import(pathToFileURL(module));
  const templates = [
    "outer",
    "inner",
    "router",
    "gauge",
    "testbench",
    "trigger",
    "clock",
    "reservoir",
    "index",
    "meter",
    "dock",
    "reader",
    "session",
    "carrier",
    "selector",
    "interlock",
    "workcell",
    "recorder",
    "unknown",
  ];
  const orders = {};
  let failures = 0;
  for (const template of templates) {
    for (const angle of [20, 22, 30, 32, 40, 42, 50, 52, 60, 62, 70]) {
      for (const apart of [false, true]) {
        const { p, parts } = mechanismFigure(template, { angle, apart });
        const R = A.recorder(p, { ground: (s) => A.boundsOf(s).min[2] <= -12 });
        parts.forEach((part, i) =>
          R.put({
            name: `${template}:${i}:${part.cls}`,
            key: part.depth,
            shapes: [R.solid({ ...part.shape.world, name: `${template}:${i}:${part.cls}` })],
            svg: `<path d="${part.shape.fill}"/>`,
          }),
        );
        A.settle(R, p, { step: 0.5 });
        const depth = A.depthOrder(R.items, p, {
          overlaps: R.settled.overlaps,
          solved: R.settled.solved,
        });
        if (depth.problems.length > 0) {
          console.error(template, angle, apart, "depth problems", depth.problems.length);
          failures += depth.problems.length;
        }
        if (angle === 42 && !apart) {
          const result = A.auditOrExit(R, p, { argv: ["--audit"] });
          failures += A.failures(result);
        }
        orders[`${template}:${apart}:${angle}`] = {
          fingerprint: geometryFingerprint(parts),
          order: R.items
            .map((v, i) => [v.key, i])
            .toSorted((a, b) => a[0] - b[0] || a[1] - b[1])
            .map((v) => v[1]),
        };
      }
    }
    console.log("settled", template);
  }
  if (failures) {
    throw new Error(`${failures} geometry failures; previous orders preserved.`);
  }
  writeFileSync(
    target,
    "// Generated by scripts/settle-loop-anatomy.mjs; do not edit.\nexport const geometryOrders = " +
      JSON.stringify(orders) +
      ";\n",
  );
  const linted = spawnSync("pnpm", ["exec", "oxlint", "--fix", fileURLToPath(target)], {
    cwd: new URL("../ui/", import.meta.url),
    stdio: "inherit",
  });
  if (linted.error || linted.status !== 0) {
    throw new Error("Generated geometry lint failed.", { cause: linted.error });
  }
  const formatted = spawnSync("pnpm", ["exec", "oxfmt", "--write", fileURLToPath(target)], {
    cwd: new URL("../ui/", import.meta.url),
    stdio: "inherit",
  });
  if (formatted.error || formatted.status !== 0) {
    throw new Error("Generated geometry formatting failed.", { cause: formatted.error });
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
